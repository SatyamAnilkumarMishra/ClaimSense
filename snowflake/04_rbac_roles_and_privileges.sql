-- ============================================================================
-- ClaimSense Snowflake Script 04: Role-Based Access Control (RBAC)
-- ============================================================================

USE ROLE SECURITYADMIN;

-- 1. Create Functional Business Roles
CREATE ROLE IF NOT EXISTS CLAIMS_ANALYST
    COMMENT = 'Business analysts reading curated marts without access to staging or raw PII';

CREATE ROLE IF NOT EXISTS CLAIMS_DATA_ENGINEER
    COMMENT = 'Data engineers managing ETL staging, streams, and automated tasks';

CREATE ROLE IF NOT EXISTS CLAIMS_SIU_INVESTIGATOR
    COMMENT = 'Special Investigation Unit personnel inspecting fraud risk scores';

-- 2. Role Hierarchy: Grant Functional Roles to SYSADMIN
GRANT ROLE CLAIMS_ANALYST TO ROLE SYSADMIN;
GRANT ROLE CLAIMS_DATA_ENGINEER TO ROLE SYSADMIN;
GRANT ROLE CLAIMS_SIU_INVESTIGATOR TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

-- 3. Grant Warehouse Usage
GRANT USAGE ON WAREHOUSE CLAIMSENSE_WH TO ROLE CLAIMS_ANALYST;
GRANT USAGE ON WAREHOUSE CLAIMSENSE_WH TO ROLE CLAIMS_DATA_ENGINEER;
GRANT USAGE ON WAREHOUSE CLAIMSENSE_WH TO ROLE CLAIMS_SIU_INVESTIGATOR;

-- 4. Grant Database & Schema Access
GRANT USAGE ON DATABASE CLAIMSENSE_DB TO ROLE CLAIMS_ANALYST;
GRANT USAGE ON DATABASE CLAIMSENSE_DB TO ROLE CLAIMS_DATA_ENGINEER;
GRANT USAGE ON DATABASE CLAIMSENSE_DB TO ROLE CLAIMS_SIU_INVESTIGATOR;

-- Analysts can ONLY see MART schema (Principle of Least Privilege)
GRANT USAGE ON SCHEMA CLAIMSENSE_DB.MART TO ROLE CLAIMS_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA CLAIMSENSE_DB.MART TO ROLE CLAIMS_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CLAIMSENSE_DB.MART TO ROLE CLAIMS_ANALYST;

-- Data Engineers have ALL privileges on STAGING and MART schemas
GRANT ALL PRIVILEGES ON SCHEMA CLAIMSENSE_DB.STAGING TO ROLE CLAIMS_DATA_ENGINEER;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA CLAIMSENSE_DB.STAGING TO ROLE CLAIMS_DATA_ENGINEER;
GRANT ALL PRIVILEGES ON SCHEMA CLAIMSENSE_DB.MART TO ROLE CLAIMS_DATA_ENGINEER;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA CLAIMSENSE_DB.MART TO ROLE CLAIMS_DATA_ENGINEER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE CLAIMS_DATA_ENGINEER;

-- SIU Investigators have SELECT on Marts + Staging Claims
GRANT USAGE ON SCHEMA CLAIMSENSE_DB.MART TO ROLE CLAIMS_SIU_INVESTIGATOR;
GRANT SELECT ON ALL TABLES IN SCHEMA CLAIMSENSE_DB.MART TO ROLE CLAIMS_SIU_INVESTIGATOR;
GRANT USAGE ON SCHEMA CLAIMSENSE_DB.STAGING TO ROLE CLAIMS_SIU_INVESTIGATOR;
GRANT SELECT ON TABLE CLAIMSENSE_DB.STAGING.STG_FACT_CLAIMS TO ROLE CLAIMS_SIU_INVESTIGATOR;
GRANT SELECT ON TABLE CLAIMSENSE_DB.STAGING.STG_DIM_CUSTOMER TO ROLE CLAIMS_SIU_INVESTIGATOR;
